create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- =========================
-- Tables
-- =========================

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role public.user_role not null default 'viewer',
  phone text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.locations (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  address text,
  city text,
  client_name text,
  contact text,
  phone text,
  yandex_maps_url text,
  working_hours text,
  notes text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.location_tags (
  id uuid primary key default gen_random_uuid(),
  location_id uuid not null references public.locations(id) on delete cascade,
  tag text not null,
  created_at timestamptz not null default now(),
  constraint location_tags_location_tag_unique unique (location_id, tag)
);

create table if not exists public.requests (
  id uuid primary key default gen_random_uuid(),
  request_number bigint generated by default as identity unique,
  location_id uuid references public.locations(id) on delete set null,
  title text,
  description text not null,
  request_type public.request_type not null default 'other',
  urgency public.urgency_level not null default 'normal',
  status public.request_status not null default 'needs_planning',
  source public.request_source not null default 'manual',
  created_by uuid references public.profiles(id) on delete set null,
  reported_by_name text,
  planned_date date,
  start_time time,
  end_time time,
  queue_position integer,
  assigned_to uuid references public.profiles(id) on delete set null,
  outsource_contractor text,
  outsource_comment text,
  manager_comment text,
  executor_comment text,
  closed_at timestamptz,
  closed_by uuid references public.profiles(id) on delete set null,
  close_result public.close_result,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint requests_queue_position_positive check (queue_position is null or queue_position > 0)
);

create table if not exists public.request_comments (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.requests(id) on delete cascade,
  author_id uuid references public.profiles(id) on delete set null,
  body text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.request_events (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.requests(id) on delete cascade,
  actor_id uuid references public.profiles(id) on delete set null,
  event_type text not null,
  from_value jsonb,
  to_value jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.attachments (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.requests(id) on delete cascade,
  uploaded_by uuid references public.profiles(id) on delete set null,
  source public.attachment_source not null default 'manual',
  storage_path text not null,
  file_name text,
  mime_type text,
  file_type public.attachment_file_type not null default 'other',
  created_at timestamptz not null default now()
);

