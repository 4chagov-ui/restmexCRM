create or replace view public.new_requests_view as
select
  r.*,
  l.name as location_name,
  l.address as location_address,
  l.city as location_city,
  assignee.full_name as assigned_to_name,
  creator.full_name as created_by_name
from public.requests r
left join public.locations l on l.id = r.location_id
left join public.profiles assignee on assignee.id = r.assigned_to
left join public.profiles creator on creator.id = r.created_by
where r.status in ('needs_planning', 'needs_review');

create or replace view public.mechanic_current_tasks_view as
select
  r.*,
  l.name as location_name,
  l.address as location_address,
  l.city as location_city,
  assignee.full_name as assigned_to_name
from public.requests r
left join public.locations l on l.id = r.location_id
left join public.profiles assignee on assignee.id = r.assigned_to
where r.planned_date = current_date
  and r.status in ('planned', 'in_progress', 'waiting_client')
order by
  r.queue_position asc nulls last,
  case r.urgency
    when 'critical' then 1
    when 'high' then 2
    when 'normal' then 3
    when 'low' then 4
  end,
  r.created_at asc;

create or replace view public.outsource_requests_view as
select
  r.*,
  l.name as location_name,
  l.address as location_address,
  l.city as location_city,
  assignee.full_name as assigned_to_name
from public.requests r
left join public.locations l on l.id = r.location_id
left join public.profiles assignee on assignee.id = r.assigned_to
where r.status = 'specialist_on_way';

create or replace view public.closed_requests_view as
select
  r.*,
  l.name as location_name,
  l.address as location_address,
  l.city as location_city,
  assignee.full_name as assigned_to_name,
  closer.full_name as closed_by_name
from public.requests r
left join public.locations l on l.id = r.location_id
left join public.profiles assignee on assignee.id = r.assigned_to
left join public.profiles closer on closer.id = r.closed_by
where r.status in ('done', 'cancelled', 'duplicate', 'not_actual');

